import React, { useEffect, useState } from "react";
import type { BarrierItem } from "./BarrierList.js";

interface DiffModalProps {
  barrier: BarrierItem | null;
  onClose: () => void;
}

export const DiffModal: React.FC<DiffModalProps> = ({ barrier, onClose }) => {
  const [copied, setCopied] = useState<boolean>(false);

  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
    };
    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, [onClose]);

  if (!barrier || !barrier.fix) return null;

  const { fix } = barrier;

  // Extract code content from any schema format (FixProposal body or legacy properties)
  let codeContent = fix.body || "";
  if (!codeContent) {
    if (fix.cssRule) {
      codeContent = fix.cssRule;
    } else if (fix.attributes) {
      codeContent = `// Attribute Patch\nconst target = document.querySelector("${fix.targetSelector || barrier.selector}");\n` +
        Object.entries(fix.attributes)
          .map(([k, v]) => `target.setAttribute("${k}", "${v}");`)
          .join("\n");
    } else if (fix.htmlReplacement) {
      codeContent = fix.htmlReplacement;
    } else if (fix.scriptContent) {
      codeContent = fix.scriptContent;
    }
  }

  const patchType = (fix.patchType || "css").toUpperCase();
  const explanation = fix.rationale || fix.explanation || "Accessibility remediation generated by NVIDIA Nemotron Ultra.";
  const targetSelector = fix.targetSelector || barrier.selector;

  const handleCopy = () => {
    if (!codeContent) return;
    navigator.clipboard.writeText(codeContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div
      role="dialog"
      aria-modal="true"
      aria-labelledby="diff-modal-title"
      style={{
        position: "fixed",
        inset: 0,
        backgroundColor: "rgba(11, 14, 20, 0.85)",
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
        zIndex: 200,
        padding: "20px",
      }}
      onClick={onClose}
    >
      <div
        style={{
          backgroundColor: "var(--color-surface-1)",
          border: "1px solid var(--color-border-subdued)",
          borderRadius: "var(--radius-lg)",
          maxWidth: "700px",
          width: "100%",
          maxHeight: "90vh",
          display: "flex",
          flexDirection: "column",
          boxShadow: "var(--shadow-modal)",
          overflow: "hidden",
        }}
        onClick={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div
          style={{
            padding: "16px 20px",
            borderBottom: "1px solid var(--color-border-subdued)",
            display: "flex",
            justifyContent: "space-between",
            alignItems: "center",
            backgroundColor: "var(--color-surface-1)",
          }}
        >
          <div>
            <div
              style={{
                fontSize: "10px",
                fontWeight: 600,
                letterSpacing: "0.06em",
                textTransform: "uppercase",
                color: "var(--color-text-muted)",
                fontFamily: "var(--font-mono)",
              }}
            >
              {barrier.verified ? "Verified Chromium Fix" : "Nemotron Ultra Fix Proposal"}
            </div>
            <h3
              id="diff-modal-title"
              style={{
                fontSize: "14px",
                fontWeight: 600,
                color: "var(--color-text-primary)",
                fontFamily: "var(--font-mono)",
                marginTop: "2px",
              }}
            >
              {barrier.detectorId} · {barrier.selector}
            </h3>
          </div>

          <button
            onClick={onClose}
            aria-label="Close modal"
            style={{
              padding: "4px 8px",
              borderRadius: "var(--radius-xs)",
              backgroundColor: "var(--color-surface-2)",
              border: "1px solid var(--color-border-subdued)",
              color: "var(--color-text-muted)",
              fontSize: "11px",
              fontFamily: "var(--font-mono)",
              cursor: "pointer",
            }}
          >
            Esc ✕
          </button>
        </div>

        {/* Content body */}
        <div
          style={{
            padding: "20px",
            overflowY: "auto",
            display: "flex",
            flexDirection: "column",
            gap: "14px",
          }}
        >
          {/* Verification Verdict Banner */}
          <div
            style={{
              padding: "12px 14px",
              borderRadius: "var(--radius-xs)",
              backgroundColor: barrier.verified
                ? "var(--color-accent-emerald-subtle)"
                : "rgba(245, 158, 11, 0.08)",
              border: `1px solid ${
                barrier.verified
                  ? "var(--color-accent-emerald-border)"
                  : "var(--color-severity-major-border)"
              }`,
              fontSize: "12px",
            }}
          >
            <div
              style={{
                color: barrier.verified
                  ? "var(--color-accent-emerald)"
                  : "var(--color-severity-major)",
                fontWeight: 600,
                marginBottom: "3px",
                display: "flex",
                alignItems: "center",
                gap: "6px",
                fontFamily: "var(--font-mono)",
                textTransform: "uppercase",
                letterSpacing: "0.04em",
              }}
            >
              {barrier.verified ? "✓ Deterministic Verification Passed" : "⚠ Proposed Patch · Verification Pending / Unconfirmed"}
            </div>
            <div style={{ color: "var(--color-text-secondary)", lineHeight: 1.5, fontSize: "12px" }}>
              {barrier.verificationEvidence ||
                (barrier.verified
                  ? "BlindSpot injected this patch in-memory into Playwright Chromium, re-ran the full keyboard crawl, and confirmed that the barrier was eliminated with zero regressions."
                  : "BlindSpot generated this patch using Nemotron Ultra. During in-browser re-crawl, the barrier was not confirmed eliminated or regressions were detected. Review recommended.")}
            </div>
          </div>

          {/* Rationale */}
          <div>
            <div
              style={{
                fontSize: "11px",
                fontWeight: 600,
                color: "var(--color-text-muted)",
                fontFamily: "var(--font-mono)",
                textTransform: "uppercase",
                letterSpacing: "0.04em",
                marginBottom: "4px",
              }}
            >
              Model Rationale (Nemotron Ultra)
            </div>
            <p style={{ fontSize: "13px", color: "var(--color-text-primary)", lineHeight: 1.5 }}>
              {explanation}
            </p>
          </div>

          {/* Target Element */}
          <div
            style={{
              padding: "8px 12px",
              borderRadius: "var(--radius-xs)",
              backgroundColor: "var(--color-surface-2)",
              border: "1px solid var(--color-border-subdued)",
              display: "flex",
              justifyContent: "space-between",
              alignItems: "center",
              fontSize: "11px",
              fontFamily: "var(--font-mono)",
            }}
          >
            <span style={{ color: "var(--color-text-muted)" }}>Target Selector:</span>
            <code style={{ color: "var(--color-border-focus)", fontWeight: 600 }}>{targetSelector}</code>
          </div>

          {/* Patch code viewport */}
          <div>
            <div
              style={{
                display: "flex",
                justifyContent: "space-between",
                alignItems: "center",
                padding: "8px 12px",
                backgroundColor: "var(--color-surface-3)",
                border: "1px solid var(--color-border-subdued)",
                borderBottom: "none",
                borderRadius: "var(--radius-xs) var(--radius-xs) 0 0",
              }}
            >
              <span
                style={{
                  fontSize: "11px",
                  fontFamily: "var(--font-mono)",
                  color: "var(--color-text-muted)",
                  textTransform: "uppercase",
                }}
              >
                Patch Type: <strong style={{ color: "var(--color-text-primary)" }}>{patchType}</strong>
              </span>

              <button
                onClick={handleCopy}
                style={{
                  fontSize: "11px",
                  padding: "3px 10px",
                  borderRadius: "var(--radius-xs)",
                  backgroundColor: copied ? "var(--color-accent-emerald-subtle)" : "var(--color-surface-2)",
                  border: copied ? "1px solid var(--color-accent-emerald-border)" : "1px solid var(--color-border-subdued)",
                  color: copied ? "var(--color-accent-emerald)" : "var(--color-border-focus)",
                  fontFamily: "var(--font-mono)",
                  fontWeight: 600,
                  cursor: "pointer",
                }}
              >
                {copied ? "Copied! ✓" : "Copy Patch"}
              </button>
            </div>

            <pre
              style={{
                backgroundColor: "var(--color-surface-2)",
                border: "1px solid var(--color-border-subdued)",
                borderRadius: "0 0 var(--radius-xs) var(--radius-xs)",
                padding: "14px 16px",
                fontSize: "12px",
                fontFamily: "var(--font-mono)",
                color: "#6EE7B7",
                overflowX: "auto",
                lineHeight: 1.6,
                margin: 0,
              }}
            >
              <code>{codeContent || "/* No patch body provided */"}</code>
            </pre>
          </div>
        </div>
      </div>
    </div>
  );
};
