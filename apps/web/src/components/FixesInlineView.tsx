interface ParsedDiffLine {
  type: "add" | "remove" | "context" | "header";
  oldLineNumber?: number;
  newLineNumber?: number;
  prefix: string;
  content: string;
}

function parseUnifiedDiff(diffText: string): ParsedDiffLine[] {
  if (!diffText) return [];
  const lines = diffText.split("\n");
  const result: ParsedDiffLine[] = [];
  let oldLine = 1;
  let newLine = 1;

  const isUnified = lines.some((l) => l.startsWith("---") || l.startsWith("@@"));

  if (!isUnified) {
    lines.forEach((l, idx) => {
      if (l.trim().length === 0 && idx === lines.length - 1) return;
      result.push({
        type: "add",
        newLineNumber: idx + 1,
        prefix: "+",
        content: l,
      });
    });
    return result;
  }

  for (const rawLine of lines) {
    if (rawLine.startsWith("---") || rawLine.startsWith("+++")) {
      result.push({ type: "header", prefix: "##", content: rawLine });
    } else if (rawLine.startsWith("@@")) {
      const match = rawLine.match(/@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@/);
      if (match) {
        oldLine = parseInt(match[1]!, 10);
        newLine = parseInt(match[2]!, 10);
      }
      result.push({ type: "header", prefix: "@@", content: rawLine });
    } else if (rawLine.startsWith("+")) {
      result.push({
        type: "add",
        newLineNumber: newLine++,
        prefix: "+",
        content: rawLine.slice(1),
      });
    } else if (rawLine.startsWith("-")) {
      result.push({
        type: "remove",
        oldLineNumber: oldLine++,
        prefix: "-",
        content: rawLine.slice(1),
      });
    } else {
      const content = rawLine.startsWith(" ") ? rawLine.slice(1) : rawLine;
      result.push({
        type: "context",
        oldLineNumber: oldLine++,
        newLineNumber: newLine++,
        prefix: " ",
        content,
      });
    }
  }
  return result;
}

export const FixesInlineView: React.FC<FixesInlineViewProps> = ({
  barriers,
  onOpenFullScreen,
  isSourceMode = false,
  onApplyToFolder,
}) => {
  const [copiedId, setCopiedId] = useState<string | null>(null);
  const [barrierFormat, setBarrierFormat] = useState<Record<string, "html" | "react">>({});

  const barriersWithFixes = barriers.filter(
    (b) => b.fix || b.diff || b.modifiedSource
  );

  const handleCopy = (id: string, text: string) => {
    navigator.clipboard.writeText(text);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 2000);
  };

  if (barriersWithFixes.length === 0) {
    return (
      <div
        className="neo-extruded"
        style={{
          borderRadius: "var(--radius-xl)",
          padding: "var(--space-8)",
          textAlign: "center",
          color: "var(--color-text-secondary)",
          fontSize: "var(--font-size-base)",
        }}
      >
        <p style={{ margin: "0 0 var(--space-2) 0", fontWeight: 600, color: "var(--color-text-primary)" }}>
          No automated fixes generated for this audit.
        </p>
        <p style={{ margin: 0, color: "var(--color-text-muted)" }}>
          Run the audit with "Suggest fixes and test them" enabled to produce deterministic patches.
        </p>
      </div>
    );
  }

  return (
    <div style={{ display: "flex", flexDirection: "column", gap: "var(--space-6)" }}>
      {/* Header with Help Text */}
      <div
        className="neo-extruded"
        style={{
          borderRadius: "var(--radius-xl)",
          padding: "var(--space-4) var(--space-6)",
        }}
      >
        <h2
          style={{
            fontSize: "var(--font-size-xl)",
            fontWeight: 600,
            color: "var(--color-text-primary)",
            margin: "0 0 6px 0",
          }}
        >
          Fixes ({barriersWithFixes.length})
        </h2>
        <p
          style={{
            fontSize: "var(--font-size-base)",
            color: "var(--color-text-secondary)",
            margin: 0,
            lineHeight: 1.5,
          }}
        >
          Automated patches generated by NVIDIA Nemotron Ultra and verified in an airgapped browser before presentation.
        </p>
      </div>

      {/* List of Fixes */}
      {barriersWithFixes.map((barrier) => {
        const itemDetail = getProblemDetail(barrier);
        const isVerified = barrier.status === "verified" || barrier.verified;
        const isRejected = barrier.status === "rejected";

        const statusColor = isVerified
          ? "var(--color-status-success)"
          : isRejected
          ? "var(--color-severity-blocker)"
          : "var(--color-severity-major)";

        const statusText = isVerified
          ? "Tested & Working"
          : isRejected
          ? "Verification Failed"
          : "Needs Verification";

        const statusIconType = isVerified ? "success" : isRejected ? "blocker" : "major";

        let evidenceSentence = barrier.verificationEvidence;
        if (!evidenceSentence) {
          if (isVerified) {
            evidenceSentence =
              barrier.afterCrawlSummary
                ? `Focus now reaches all ${barrier.afterCrawlSummary.stopsCount} tab stops with zero regressions.`
                : "Tested in a real browser: the barrier is eliminated with zero regressions.";
          } else if (isRejected) {
            evidenceSentence =
              barrier.rejectionReason || "Verification failed: patch introduced layout regressions or exceeded line limit.";
          } else {
            evidenceSentence = "Patch generated; verification unconfirmed in headless crawl.";
          }
        }

        const attemptsText = "1 attempt";

        const reactEquivalent =
          barrier.fix?.reactEquivalent ||
          barrier.reactEquivalent ||
          (barrier.fix?.body
            ? translateFixToReact(
                {
                  patchType: barrier.fix.patchType,
                  body: barrier.fix.body,
                  rationale: barrier.fix.rationale || barrier.fix.explanation,
                  targetSelector: barrier.selector,
                },
                { detectorId: barrier.detectorId, selector: barrier.selector }
              )
            : null);

        const currentFormat = barrierFormat[barrier.id] || "html";

        const diffText =
          barrier.diff ||
          barrier.fix?.diff ||
          barrier.fix?.body ||
          barrier.fix?.cssRule ||
          "";

        const diffLines = parseUnifiedDiff(diffText);

        return (
          <div
            key={barrier.id}
            className="neo-extruded"
            style={{
              borderRadius: "var(--radius-xl)",
              padding: "var(--space-6)",
              display: "flex",
              flexDirection: "column",
              gap: "var(--space-4)",
            }}
          >
            {/* Heading with Problem Name, Status, and Attempts */}
            <div
              style={{
                display: "flex",
                justifyContent: "space-between",
                alignItems: "flex-start",
                flexWrap: "wrap",
                gap: "var(--space-3)",
                paddingBottom: "var(--space-4)",
                borderBottom: "1px solid var(--color-border-subdued)",
              }}
            >
              <div>
                <h3
                  style={{
                    fontSize: "var(--font-size-lg)",
                    fontWeight: 600,
                    color: "var(--color-text-primary)",
                    margin: "0 0 6px 0",
                    lineHeight: 1.4,
                  }}
                >
                  {itemDetail.plainTitle}
                </h3>

                <div style={{ display: "flex", alignItems: "center", gap: "var(--space-2)", flexWrap: "wrap" }}>
                  {(() => {
                    const displayPath = barrier.filePath || barrier.fix?.filePath || barrier.likelySource?.path;
                    if (!displayPath) return null;
                    const isReact = displayPath.endsWith(".tsx") || displayPath.endsWith(".jsx");
                    return (
                      <div style={{ display: "inline-flex", alignItems: "center", gap: "6px" }}>
                        {isReact && (
                          <span
                            className="neo-pill"
                            style={{
                              fontSize: "12px",
                              fontWeight: 700,
                              padding: "2px 8px",
                              color: "var(--color-accent-primary)",
                            }}
                          >
                            React
                          </span>
                        )}
                        <span
                          className="neo-pill"
                          style={{
                            fontFamily: "var(--font-mono)",
                            fontSize: "12px",
                            fontWeight: 600,
                            color: "var(--color-accent-primary)",
                            padding: "2px 8px",
                          }}
                        >
                          {displayPath}
                        </span>
                      </div>
                    );
                  })()}

                  <code
                    className="neo-sunken"
                    style={{
                      fontFamily: "var(--font-mono)",
                      fontSize: "var(--font-size-sm)",
                      color: "var(--color-text-secondary)",
                      padding: "2px 8px",
                      borderRadius: "var(--radius-sm)",
                    }}
                  >
                    {barrier.selector}
                  </code>

                  <span style={{ fontSize: "var(--font-size-sm)", color: "var(--color-text-muted)" }}>
                    {barrier.wcagName} ({barrier.wcagId})
                  </span>
                </div>
              </div>

              {/* Status and Attempts */}
              <div style={{ display: "flex", flexDirection: "column", alignItems: "flex-end", gap: "6px" }}>
                <span
                  className="neo-pill"
                  style={{
                    display: "inline-flex",
                    alignItems: "center",
                    gap: "6px",
                    padding: "4px 12px",
                    color: statusColor,
                    fontSize: "var(--font-size-sm)",
                    fontWeight: 600,
                    border: isVerified ? "1px solid #84CC16" : undefined,
                  }}
                >
                  <StatusIcon status={statusIconType} size={14} />
                  <span>{statusText}</span>
                </span>

                <span style={{ fontSize: "12px", color: "var(--color-text-muted)", fontFamily: "var(--font-mono)" }}>
                  {attemptsText}
                </span>
              </div>
            </div>

            {/* Verification Evidence Sentence */}
            <div
              className="neo-sunken"
              style={{
                display: "flex",
                alignItems: "center",
                gap: "10px",
                padding: "var(--space-3) var(--space-4)",
                borderRadius: "var(--radius-md)",
                fontSize: "var(--font-size-sm)",
              }}
            >
              <StatusIcon status={statusIconType} size={16} />
              <span style={{ color: "var(--color-text-primary)", lineHeight: 1.5 }}>
                {evidenceSentence}
              </span>
            </div>

            {/* Format Selector Toolbar if React Equivalent Exists */}
            {reactEquivalent && (
              <div
                style={{
                  display: "flex",
                  justifyContent: "space-between",
                  alignItems: "center",
                  flexWrap: "wrap",
                  gap: "var(--space-3)",
                }}
              >
                <div style={{ display: "flex", alignItems: "center", gap: "var(--space-2)" }}>
                  <SegmentedControl<"html" | "react">
                    name={`format-${barrier.id}`}
                    ariaLabel="Patch format"
                    size="sm"
                    value={currentFormat}
                    onChange={(val) =>
                      setBarrierFormat((prev) => ({ ...prev, [barrier.id]: val }))
                    }
                    options={[
                      { value: "html", label: "HTML / DOM patch" },
                      { value: "react", label: "React (JSX / TSX)" },
                    ]}
                  />
                  <div
                    aria-live="polite"
                    className="sr-only"
                    style={{
                      position: "absolute",
                      width: "1px",
                      height: "1px",
                      padding: 0,
                      margin: "-1px",
                      overflow: "hidden",
                      clip: "rect(0, 0, 0, 0)",
                      whiteSpace: "nowrap",
                      border: 0,
                    }}
                  >
                    {currentFormat === "react" ? "React format selected" : "HTML format selected"}
                  </div>
                </div>
                <span
                  style={{
                    fontSize: "var(--font-size-xs)",
                    color: "var(--color-text-muted)",
                    fontFamily: "var(--font-mono)",
                  }}
                >
                  Target: {barrier.selector}
                </span>
              </div>
            )}

            {currentFormat === "react" && reactEquivalent ? (
              <div
                tabIndex={0}
                role="region"
                aria-label="React equivalent snippet"
                className="neo-sunken"
                style={{
                  borderRadius: "var(--radius-lg)",
                  padding: "var(--space-4)",
                  display: "flex",
                  flexDirection: "column",
                  gap: "var(--space-3)",
                  backgroundColor: "#0B1711",
                }}
              >
                <div
                  style={{
                    padding: "var(--space-2) var(--space-3)",
                    backgroundColor: "rgba(27, 94, 59, 0.2)",
                    borderLeft: "3px solid var(--color-accent-primary)",
                    borderRadius: "var(--radius-sm)",
                    fontSize: "var(--font-size-xs)",
                    color: "var(--color-text-secondary)",
                    lineHeight: 1.5,
                  }}
                >
                  <strong style={{ color: "#A3E635" }}>React (JSX / TSX)</strong>: Translated from the verified HTML patch. The browser verified the DOM change, not this JSX.
                </div>

                <pre
                  style={{
                    margin: 0,
                    padding: "var(--space-3)",
                    backgroundColor: "#070E0A",
                    border: "1px solid rgba(255, 255, 255, 0.05)",
                    borderRadius: "var(--radius-md)",
                    fontSize: "var(--font-size-sm)",
                    fontFamily: "var(--font-mono)",
                    color: "#A3E635",
                    overflowX: "auto",
                    lineHeight: 1.6,
                  }}
                >
                  <code>{reactEquivalent.code}</code>
                </pre>
              </div>
            ) : (
              /* Recessed Deep-Green Sunken Unified Diff Container */
              <div
                tabIndex={0}
                role="region"
                aria-label="Code diff viewer"
                className="neo-sunken"
                style={{
                  backgroundColor: "#0B1711",
                  border: "1px solid rgba(0, 0, 0, 0.4)",
                  borderRadius: "var(--radius-lg)",
                  overflowX: "auto",
                  fontFamily: "var(--font-mono)",
                  fontSize: "var(--font-size-sm)",
                  lineHeight: 1.5,
                  padding: "8px 0",
                }}
              >
                {diffLines.map((line, lIdx) => {
                  const isAdd = line.prefix === "+";
                  const isRemove = line.prefix === "-";
                  const isHeader = line.type === "header";

                  return (
                    <div
                      key={lIdx}
                      style={{
                        display: "grid",
                        gridTemplateColumns: "40px 40px 24px 1fr",
                        backgroundColor: isAdd
                          ? "rgba(163, 230, 53, 0.14)"
                          : isRemove
                          ? "rgba(239, 68, 68, 0.14)"
                          : isHeader
                          ? "rgba(255, 255, 255, 0.04)"
                          : "transparent",
                        color: isAdd
                          ? "#A3E635"
                          : isRemove
                          ? "#FF7B7B"
                          : isHeader
                          ? "var(--color-text-muted)"
                          : "#F6F4EE",
                        padding: "3px 12px",
                      }}
                    >
                      <span
                        style={{
                          textAlign: "right",
                          paddingRight: "8px",
                          color: "var(--color-text-muted)",
                          userSelect: "none",
                          fontSize: "12px",
                        }}
                      >
                        {line.oldLineNumber || ""}
                      </span>

                      <span
                        style={{
                          textAlign: "right",
                          paddingRight: "8px",
                          color: "var(--color-text-muted)",
                          userSelect: "none",
                          fontSize: "12px",
                        }}
                      >
                        {line.newLineNumber || ""}
                      </span>

                      <span
                        style={{
                          textAlign: "center",
                          fontWeight: 700,
                          userSelect: "none",
                        }}
                      >
                        {line.prefix}
                      </span>

                      <span style={{ whiteSpace: "pre-wrap", wordBreak: "break-all" }}>
                        {line.content}
                      </span>
                    </div>
                  );
                })}
              </div>
            )}

            {/* Action Bar */}
            <div
              style={{
                display: "flex",
                justifyContent: "space-between",
                alignItems: "center",
                flexWrap: "wrap",
                gap: "var(--space-2)",
                paddingTop: "var(--space-2)",
              }}
            >
              <div style={{ display: "flex", gap: "var(--space-2)" }}>
                <Button
                  variant="secondary"
                  size="sm"
                  onClick={() => handleCopy(barrier.id, diffText)}
                  title="Copy patch to clipboard"
                >
                  <span>{copiedId === barrier.id ? "✓ Copied" : "Copy patch"}</span>
                </Button>

                {onApplyToFolder && isSourceMode && (
                  <Button
                    variant="primary"
                    size="sm"
                    onClick={() => onApplyToFolder(barrier)}
                    title="Apply patch to working files"
                  >
                    Apply patch
                  </Button>
                )}
              </div>

              <Button
                variant="quiet"
                size="sm"
                onClick={() => onOpenFullScreen(barrier)}
                title="Open full-screen diff modal"
              >
                Inspect diff →
              </Button>
            </div>
          </div>
        );
      })}
    </div>
  );
};
